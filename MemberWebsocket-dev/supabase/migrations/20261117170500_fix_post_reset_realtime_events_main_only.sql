-- AC-001: When the operator completes a full reset, its own system-baseline
-- notifications must not leave stale public.realtime_events rows.
-- Project-specific: only MemberWebsocket-main (dbuquirnaskrwcamdxki).
-- Never executes a reset, deletes users/tenants, or clears existing events.
-- It only changes the existing guarded reset implementation for *future* resets.
--
-- Before deploying to the production database: inspect the original function,
-- maintain a DB backup and obtain an explicit approval for production changes.
DO $patch_main_reset_realtime$
DECLARE
  v_project_ref text;
  v_definition text;
  v_before text := E' perform maintenance.ensure_event_ticket_settings_baseline();\n if exists(select 1 from public.admins)';
  v_after text := E' perform maintenance.ensure_event_ticket_settings_baseline();\n -- Drop transient realtime notifications generated by system baseline restoration.\n truncate table public.realtime_events restart identity;\n if exists(select 1 from public.realtime_events) then\n   raise exception ''RESET_RESIDUAL_REALTIME_EVENTS'';\n end if;\n if exists(select 1 from public.admins)';
BEGIN
  IF pg_catalog.to_regclass('maintenance.sandbox_reset_target') IS NULL
     OR pg_catalog.to_regprocedure(
       'maintenance.execute_sandbox_database_reset(uuid,text,text)') IS NULL
  THEN
    RETURN;
  END IF;

  SELECT project_ref INTO v_project_ref
  FROM maintenance.sandbox_reset_target
  WHERE singleton IS TRUE AND sandbox_approved IS TRUE;
  IF v_project_ref IS DISTINCT FROM 'dbuquirnaskrwcamdxki' THEN
    RETURN;
  END IF;

  IF pg_catalog.to_regclass('public.realtime_events') IS NULL THEN
    RAISE EXCEPTION 'RESET_REALTIME_EVENTS_TABLE_MISSING';
  END IF;

  -- No foreign keys or truncate triggers may silently change semantics.
  IF EXISTS (
     SELECT 1 FROM pg_catalog.pg_constraint
     WHERE contype='f'
       AND (conrelid='public.realtime_events'::regclass
         OR confrelid='public.realtime_events'::regclass)
  ) OR EXISTS (
     SELECT 1 FROM pg_catalog.pg_trigger
     WHERE tgrelid='public.realtime_events'::regclass
       AND NOT tgisinternal AND (tgtype::int & 32)<>0
  ) THEN
    RAISE EXCEPTION 'RESET_REALTIME_EVENTS_DEPENDENCY_REVIEW_REQUIRED';
  END IF;

  SELECT pg_catalog.pg_get_functiondef(
    'maintenance.execute_sandbox_database_reset(uuid,text,text)'::pg_catalog.regprocedure)
  INTO v_definition;

  -- Idempotent, and fails closed if an unrelated function revision appears.
  IF pg_catalog.strpos(v_definition,v_after)>0 THEN
    RETURN;
  ELSIF pg_catalog.strpos(v_definition,v_before)>0 THEN
    EXECUTE pg_catalog.replace(v_definition,v_before,v_after);
  ELSE
    RAISE EXCEPTION 'RESET_REALTIME_EVENTS_HOOK_DEFINITION_DRIFT';
  END IF;
END
$patch_main_reset_realtime$;
