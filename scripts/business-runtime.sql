-- Business data is provisioned in a private, versioned namespace. No source rows
-- (members, bookings, tokens or admin grants) are copied from the legacy workspace.
create table platform_private.business_templates (
 version text primary key, snapshot jsonb not null, installed_at timestamptz not null default now()
);
alter table platform_private.business_templates enable row level security;
revoke all on platform_private.business_templates from public,anon,authenticated,service_role;
-- IMMUTABLE_TEMPLATE
alter table platform_private.tenants add column runtime_schema text unique;
alter table platform_private.tenants add constraint platform_runtime_schema_format
 check(runtime_schema is null or runtime_schema ~ '^business_[0-9a-f]{32}$');
alter table platform_private.tenants drop constraint platform_tenants_isolation_gate;
alter table platform_private.tenants add constraint platform_tenants_isolation_gate
 check(status<>'active' or (isolation_verified_at is not null and isolation_version='business-v1-20261019'
 and runtime_schema is not null and to_regnamespace(runtime_schema) is not null));

create function platform_private.business_sql(p_sql text,p_schema text) returns text
 language sql immutable set search_path='' as $$
 select regexp_replace(p_sql,'\mpublic\M',p_schema,'g');
$$;
revoke all on function platform_private.business_sql(text,text) from public,anon,authenticated,service_role;

create function public.platform_provision_business(p_tenant_id uuid) returns void
 language plpgsql security definer set search_path='' as $$
declare t platform_private.tenants; s text; template jsonb; obj jsonb; col jsonb;
 q text; cols text; sig text; pending jsonb; retry jsonb; progress integer; fn text;
 exposed text; prefix text;
begin
 select * into strict t from platform_private.tenants where id=p_tenant_id for update;
 if t.status='suspended' then raise exception 'TENANT_SUSPENDED'; end if;
 if t.runtime_schema is not null then return; end if;
 s:='business_'||replace(t.id::text,'-',''); prefix:=t.id::text||'/';
 select snapshot into strict template from platform_private.business_templates where version='business-v1-20261019';
 perform set_config('search_path',format('%I,extensions,pg_temp',s),true);
 execute format('create schema %I',s);
 execute format('revoke all on schema %I from public,anon,authenticated',s);
 execute format('grant usage on schema %I to service_role',s);
 for obj in select value from jsonb_array_elements(coalesce(template->'sequences','[]')) loop
  if not exists(select 1 from jsonb_array_elements(template->'tables') jt cross join lateral jsonb_array_elements(jt->'columns') jc
    where jc->>'identity'<>'' and (jt->>'name')||'_'||(jc->>'name')||'_seq'=obj->>'name') then
   execute format('create sequence %I.%I',s,obj->>'name');
  end if;
 end loop;
 for obj in select value from jsonb_array_elements(template->'tables') loop
  select string_agg(format('%I %s%s%s',c->>'name',platform_private.business_sql(c->>'type',s),
   case when c->>'generated'='s' then ' generated always as ('||platform_private.business_sql(c->>'default',s)||') stored'
    when c->>'identity'='a' then ' generated always as identity'
    when c->>'identity'='d' then ' generated by default as identity' else '' end,
   case when (c->>'notNull')::boolean then ' not null' else '' end),',') into cols
   from jsonb_array_elements(obj->'columns') c;
  execute format('create table %I.%I (%s)',s,obj->>'name',cols);
  execute format('alter table %I.%I enable row level security',s,obj->>'name');
 end loop;
 -- Storage is shared physically, with an enforced UUID prefix at the storage
 -- adapter AND a filtered SQL view; existing removal/cleanup RPCs see relative paths.
 execute format('create view %I.runtime_storage_objects with (security_invoker=true) as
  select (jsonb_populate_record(null::storage.objects,to_jsonb(o)||jsonb_build_object(''name'',substring(o.name from %s)))).*
  from storage.objects o where starts_with(o.name,%L)',s,length(prefix)+1,prefix);
 execute format('create table %I.runtime_line_settings(setting_key text primary key,value_text text,setting_type text not null default ''public'')',s);
 execute format('alter table %I.runtime_line_settings enable row level security',s);
 -- Resolve declaration cycles before validating and exercising the namespace.
 perform set_config('check_function_bodies','off',true);
 for obj in select value from jsonb_array_elements(template->'functions') loop
  fn:=obj->>'name'; q:=platform_private.business_sql(obj->>'definition',s);
  q:=replace(q,'storage.objects',format('%I.runtime_storage_objects',s));
  q:=replace(q,'line_config.settings',format('%I.runtime_line_settings',s));
  if fn in ('get_line_messaging_token','get_grant_dispatch_secret','get_e2e_artifact_retention_secret') then
   q:=format('create function %I.%I() returns text language sql set search_path='''' as $stub$ select null::text $stub$',s,fn);
  elsif fn='booking_notification_config' then
   q:=format('create function %I.%I() returns jsonb language sql set search_path='''' as $stub$ select ''{}''::jsonb $stub$',s,fn);
  elsif fn='notice_dispatch' then
   q:=format('create function %I.%I(p_limit integer default 20) returns integer language sql set search_path='''' as $stub$ select 0 $stub$',s,fn);
  elsif fn='admin_e2e_automation_health' then
   q:=format('create function %I.%I() returns jsonb language sql set search_path='''' as $stub$ select jsonb_build_object(''checkedAt'',now(),''jobs'',''[]''::jsonb,''scope'',''isolated-business'') $stub$',s,fn);
  end if;
  if q ~ '\m(public|platform_private|line_config|vault|cron)\.' then raise exception 'UNSCOPED_BUSINESS_FUNCTION: %',fn; end if;
  execute q;
 end loop;
 perform set_config('check_function_bodies','on',true);
 for obj in select value from jsonb_array_elements(template->'tables') loop
  for col in select value from jsonb_array_elements(obj->'columns') where value->>'default' is not null and value->>'generated'='' loop
   execute format('alter table %I.%I alter column %I set default %s',s,obj->>'name',col->>'name',platform_private.business_sql(col->>'default',s));
  end loop;
 end loop;
 for obj in select value from jsonb_array_elements(template->'constraints') where value->>'type' not in ('f','t') loop
  execute format('alter table %I.%I add constraint %I %s',s,obj->>'table',obj->>'name',platform_private.business_sql(obj->>'definition',s));
 end loop;
 for obj in select value from jsonb_array_elements(template->'constraints') where value->>'type'='f' loop
  execute format('alter table %I.%I add constraint %I %s',s,obj->>'table',obj->>'name',platform_private.business_sql(obj->>'definition',s));
 end loop;
 for obj in select value from jsonb_array_elements(template->'indexes') loop
  execute platform_private.business_sql(obj->>'definition',s);
 end loop;
 for obj in select value from jsonb_array_elements(template->'triggers') loop
  execute platform_private.business_sql(obj->>'definition',s);
 end loop;
 -- Only fresh defaults. Merchant content and member/business records start empty.
 execute format('insert into %I.admins(line_user_id,display_name,role,status) values($1,$2,''admin'',''active'')',s) using t.owner_line_user_id,t.name;
 foreach fn in array array['booking_settings','event_ticket_settings','point_card_settings','test_mode_settings'] loop
  execute format('insert into %I.%I default values',s,fn);
 end loop;
 execute format('insert into %I.notice_config(id,enabled) values(true,true)',s);
 execute format('insert into %I.membership_tier_settings(tier_key,tier_label,required_service_minutes,style_key) values
  (''general'',''一般會員'',0,''forest''),(''silver'',''銀級會員'',600,''ocean''),(''gold'',''金級會員'',1800,''gold''),(''platinum'',''白金會員'',3600,''platinum'')',s);
 -- Existing booking validation requires its internal arrival buffer. This is
 -- infrastructure, not a merchant's offered service or copied business data.
 execute format('insert into %I.booking_services(id,title,description,duration_minutes,price_amount,counts_toward_membership,is_active,created_by)
  values(''00000000-0000-4000-8000-000000000010'',''到店準備'',''系統預約準備時間'',10,0,false,true,''system'')',s);
 -- The template does not publish legal text on a merchant's behalf. Terms may
 -- be configured in the existing membership editor before members join.
 execute format('revoke all on all tables in schema %I from public,anon,authenticated',s);
 execute format('revoke all on all sequences in schema %I from public,anon,authenticated',s);
 execute format('revoke all on all functions in schema %I from public,anon,authenticated',s);
 execute format('grant select,insert,update,delete on all tables in schema %I to service_role',s);
 execute format('grant usage,select on all sequences in schema %I to service_role',s);
 execute format('grant execute on all functions in schema %I to service_role',s);
 -- Structural assertions are part of the same transaction. Any missed FK,
 -- trigger, default or function namespace aborts approval rather than opening it.
 if exists(select 1 from pg_constraint c join pg_class r on r.oid=c.conrelid join pg_namespace n on n.oid=r.relnamespace
   join pg_class ref on ref.oid=c.confrelid where n.nspname=s and c.contype='f' and ref.relnamespace<>n.oid)
 then raise exception 'CROSS_BUSINESS_FOREIGN_KEY'; end if;
 if exists(select 1 from pg_attrdef d join pg_class r on r.oid=d.adrelid join pg_namespace n on n.oid=r.relnamespace
   where n.nspname=s and pg_get_expr(d.adbin,d.adrelid) ~ '\mpublic\.') then raise exception 'UNSCOPED_BUSINESS_DEFAULT'; end if;
 -- An actual write exercises member IDs, defaults and all membership triggers.
 -- It is rolled back locally; no synthetic member is retained in the workspace.
 begin
  execute format('insert into %I.members(line_user_id,display_name,member_code) values($1,''provisioning-check'',%I.new_public_id(''SMOKE''))',s,s) using 'U00000000000000000000000000000000';
  raise exception 'BUSINESS_SMOKE_ROLLBACK' using errcode='ZX001';
 exception when sqlstate 'ZX001' then null; end;
 select split_part(v,'=',2) into exposed from pg_roles r cross join lateral unnest(coalesce(r.rolconfig,'{}')) v
  where r.rolname='authenticator' and v like 'pgrst.db_schemas=%';
 exposed:=coalesce(nullif(exposed,''),'public,graphql_public');
 if not s=any(string_to_array(replace(exposed,' ',''),',')) then
  execute format('alter role authenticator set pgrst.db_schemas=%L',exposed||','||s);
 end if;
 perform pg_notify('pgrst','reload config'); perform pg_notify('pgrst','reload schema');
 update platform_private.tenants set runtime_schema=s,status='active',isolation_verified_at=clock_timestamp(),
  isolation_version='business-v1-20261019',updated_at=clock_timestamp() where id=t.id;
 insert into platform_private.audit_events(actor,tenant_id,action,detail)
 values(t.updated_by,t.id,'BUSINESS_PROVISIONED',jsonb_build_object('version','business-v1-20261019','tables',jsonb_array_length(template->'tables'),'functions',jsonb_array_length(template->'functions')));
end $$;
revoke all on function public.platform_provision_business(uuid) from public,anon,authenticated;
grant execute on function public.platform_provision_business(uuid) to service_role;

create function public.platform_business_context(p_actor text default null,p_slug text default null) returns jsonb
 language sql security invoker set search_path='' as $$
 select to_jsonb(t) from platform_private.tenants t
 where (p_slug is not null and t.slug=p_slug) or (p_slug is null and t.owner_line_user_id=p_actor);
$$;
create function public.platform_business_credentials(p_tenant_id uuid) returns jsonb
 language sql security invoker set search_path='' as $$
 select envelope from platform_private.tenant_secrets where tenant_id=p_tenant_id;
$$;
create function public.platform_active_businesses() returns setof jsonb
 language sql security invoker set search_path='' as $$
 select to_jsonb(t) from platform_private.tenants t where status='active' and runtime_schema is not null;
$$;
revoke all on function public.platform_business_context(text,text),public.platform_business_credentials(uuid),public.platform_active_businesses() from public,anon,authenticated;
grant execute on function public.platform_business_context(text,text),public.platform_business_credentials(uuid),public.platform_active_businesses() to service_role;

-- Every business keeps its own issuance and reminder jobs. Dispatch only runs
-- after that merchant saves credentials; secrets never appear in job arguments.
create function public.platform_tick_businesses() returns integer
 language plpgsql security definer set search_path='' as $$
declare t record; project_url text; booking_secret text; grant_secret text; due boolean; processed integer:=0;
begin
 select decrypted_secret into project_url from vault.decrypted_secrets where name='project_url' order by updated_at desc limit 1;
 select decrypted_secret into booking_secret from vault.decrypted_secrets where name='BOOKING_NOTIFICATION_DISPATCH_SECRET' order by updated_at desc limit 1;
 select decrypted_secret into grant_secret from vault.decrypted_secrets where name='GRANT_MESSAGE_DISPATCH_SECRET' order by updated_at desc limit 1;
 for t in select id,slug,runtime_schema,features,credentials_configured from platform_private.tenants where status='active' and runtime_schema is not null loop
  begin
   if (t.features->>'events')::boolean then execute format('select %I.issue_fixed_tickets()',t.runtime_schema); end if;
   if (t.features->>'booking')::boolean then
    execute format('select %I.notice_sync_day_before_reminders()',t.runtime_schema);
    execute format('select exists(select 1 from %I.notice_outbox where status in (''pending'',''sending'') and next_attempt_at<=now())',t.runtime_schema) into due;
    if due and t.credentials_configured and project_url is not null and booking_secret is not null then
     perform net.http_post(url:=rtrim(project_url,'/')||'/functions/v1/booking-line-notifications',
      headers:=jsonb_build_object('Content-Type','application/json','x-dispatch-secret',booking_secret),body:=jsonb_build_object('business',t.slug),timeout_milliseconds:=10000);
    end if;
   end if;
   if ((t.features->>'events')::boolean or (t.features->>'membership')::boolean or (t.features->>'points')::boolean) and t.credentials_configured then
    execute format('select exists(select 1 from %I.scheduled_grant_messages where status=''pending'' and scheduled_for<=now())',t.runtime_schema) into due;
    if due and project_url is not null and grant_secret is not null then
     perform net.http_post(url:=rtrim(project_url,'/')||'/functions/v1/scheduled-grant-messages',
      headers:=jsonb_build_object('Content-Type','application/json','x-dispatch-secret',grant_secret),body:=jsonb_build_object('business',t.slug),timeout_milliseconds:=10000);
    end if;
   end if;
   execute format('delete from %I.realtime_events where created_at<clock_timestamp()-interval ''7 days''',t.runtime_schema);
   processed:=processed+1;
  exception when others then
   insert into platform_private.audit_events(actor,tenant_id,action,detail)values('system',t.id,'BUSINESS_JOB_FAILED',jsonb_build_object('code',sqlstate));
  end;
 end loop;
 return processed;
end $$;
revoke all on function public.platform_tick_businesses() from public,anon,authenticated;
grant execute on function public.platform_tick_businesses() to service_role;
do $$ begin
 if to_regprocedure('cron.schedule(text,text,text)') is not null then
  perform cron.schedule('platform-business-runtime','* * * * *','select public.platform_tick_businesses();');
 end if;
end $$;

-- APPROVAL_FUNCTION

-- Previously approved applications gain the same isolated workspace. Existing
-- business rows and public.admins are untouched.
do $$ declare t record; begin
 for t in select id from platform_private.tenants where status='pending_provisioning' loop
  perform public.platform_provision_business(t.id);
 end loop;
end $$;
